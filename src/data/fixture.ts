/** A later canon snapshot used by impact-analysis tests and the comparison UI. */
export function correctedFixtureSnapshot(): CanonSnapshot {
  const corrected = fixtureSnapshot.objects.map((object) => {
    if (object.id !== "char-amara" || object.kind !== "character") return object;
    return {
      ...object,
      ageRange: "35–38",
      version: object.version + 1,
      updatedAt: CREATED_AT + 86_400_000,
    };
  });
  return createSnapshot(
    {
      projectId: PROJECT_ID,
      label: "Canon after Amara age correction",
      meta: fixtureSnapshot.meta,
      objects: corrected,
    },
    CREATED_AT + 86_400_000,
  );
}
